// ---- この形にした理由 ----
// 品物は「系統（公開）」と「品質（非公開）」でできている。
//   系統  … 🏺壺もの／🖼絵もの／💎光もの。**開場から全員に見えている**。
//           （名前は「〜もの」でそろえてある。相場の帯に3つ並んだとき、
//             同じ種類の言葉として一目で読めるように）
//           同じ系統が落札されるたびに、その系統の相場が上がる（それが逆転の芯）
//   品質  … 上物(+3)／並物(+1)／偽物(-2)。**落札が決まるまで誰にも配らない**
//
// ヒントは3段階。**全員が同じものを、同じ瞬間に受け取る**（個人ごとの断片ではない）。
//   ① 見た目（開場時）… 品質によらない。その品がどう見えるか
//   ② ③ 段階ヒント     … **品質ごとに違う**。ここに情報がある。
//                        競りが進むにつれて、①→②→③と全員に開いていく
//
// 段階ヒントを品質ごとに書き分けているのは、
// 「ヒントが品質と矛盾しない」を、データの形そのもので守るため。
// 品質に関わらず同じヒントにすると、偽物なのに「作者の落款がある」のような
// 嘘を出してしまう（遊ぶ人は嘘のヒントを疑えないので、これは事故になる）。
//
// 正体（reveal）は開示の瞬間にだけ配る。品質ごとに1つ。
//
// 文言の決めごと：
//   ・上物 … 手入れ・由来・作り手の気配。「良い」とは書かず、良さの跡だけを書く
//   ・並物 … 使われてきた跡。悪くはないが、特別でもない
//   ・偽物 … 新しすぎる／数が多すぎる／においや手ざわりが合わない。
//            **持ち主を責めない**（「よくある間違い」として書く）

