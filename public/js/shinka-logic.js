// shinka-logic.js — カセット「進化じゃんけん」のルール層（指示55-②）
//
// 設計の芯は rcard-logic.js / falsetrue-logic.js と同じ：
// **DOM も socket.io も知らない。**Node.js から require できる純粋な計算だけを置く。
//
// ---- 遊び方 ----
// 全員が最下段から始める。同じ段の人どうしで自動的に1v1のじゃんけん。
// 勝てば1つ上の段へ。2連敗で1つ下がる（最下段は落ちない）。
// 最初に最終形まで進化した人が優勝。
//
// ---- なぜ id が `shinka` なのか（落とし穴23・5） ----
// `janken` は**すごろくのミニゲームが先に使っている**
//（`sugoroku-mini.js:58`・`index.html:14691`・`:15739`・`:21394` の4か所）。
// テーマ名は `^[a-z]+$` 縛り（`tests/design-tokens.js:110`）なので `evo-janken` も使えない。
// `sugoroku` と同じ「ローマ字の日本語」に寄せて `shinka`（進化）にした。
// 着手前に `grep -ro "'shinka'"` で0件を確かめてある。
//
// ---- ここに置かないもの ----
// ・**出した手**は、進行役（shinka-room.js）が `room.shinka.封じた手` に持つ。
//   この層は「どちらが勝つか」を答えるまで
// ・段階（phase）の進み方・締め切り・誰に何を配るか も進行役の仕事

