// ui-text.js — 共通の言い回し（第39弾 2-5）
//
// **同じ意味のボタンを、画面ごとに言い換えない。**
// 「とじる」「閉じる」「閉」がばらばらに出ると、
// 遊ぶ人は毎回「これは同じ意味か？」を判断しながら押すことになる。
//
// 正本は docs/デザインの正本.md 10。
// ここに無い語を画面に直書きしていないかは tests/ui-text.js が機械照合する。

(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.UiText = factory();
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /**
   * 共通ボタンの語。**画面ごとに言い換えない。**
   * 迷ったらここに足す（増やす時は正本の表にも行を足す）。
   */
  var WORDS = {
    start:   'はじめる',
    back:    'もどる',
    stop:    'やめる',
    close:   'とじる',
    ready:   '準備OK',
    cancel:  'キャンセル',
    create:  'つくる',
    enter:   '入る',
    ok:      'OK',
    // 判断を聞くダイアログの主ボタン。
    // 「OK/キャンセル」だと、何がOKなのかがボタンから読み取れないので、
    // なるべく動詞（「出す」「閉じる」）を渡してもらう。これは最後の逃げ道
    yes:     'はい'
  };

  /**
   * 言い換えの見張り。
   * ここに並んだ語が画面に出ていたら、正本の語に直す合図。
   * （「閉じる」は正本では「とじる」。ひらがな寄りの決めごと）
   */
  var BANNED = [
    { 見つけたら: '閉じる', 正本: 'とじる' },
    { 見つけたら: '戻る',   正本: 'もどる' },
    { 見つけたら: '開始',   正本: 'はじめる' },
    { 見つけたら: '中止',   正本: 'やめる' },
    { 見つけたら: '作成',   正本: 'つくる' },
    { 見つけたら: '参加する', 正本: '入る' }
  ];

  /** 専門用語の言い換え（正本10）。遊ぶ人の前に出してはいけない語 */
  var JARGON = [
    { 用語: 'モジュール', 言い換え: 'しかけ' },
    { 用語: 'フェーズ',   言い換え: '場面' },
    { 用語: 'ホスト',     言い換え: '進行役' },
    { 用語: 'ルーム',     言い換え: '部屋' },
    { 用語: 'プレイヤー', 言い換え: '（そのままでよい・すでに定着）', 除外: true }
  ];

  /**
   * うまくいかなかった時の知らせ（第40弾 2-2）。
   *
   * **「失敗しました」と書かない。** 遊んでいる人は何も失敗していない。
   * 手元で起きた事実だけを言う。原則C（責める時は静かに）。
   *
   * | 直す前 | 直したあと | なぜ |
   * |---|---|---|
   * | 保存に失敗しました | 保存できませんでした | 人のしくじりに聞こえない |
   * | エラーが発生しました | うまくいきませんでした | 「エラー」は遊ぶ人の言葉ではない |
   * | 取得に失敗しました | 読み込めませんでした | 同上 |
   * | 再試行してください | 少し待ってから、もう一度ためせます | 命令形の突き放しをやめる |
   */
  var MSG = {
    保存できない:   '保存できませんでした',
    読み込めない:   '読み込めませんでした',
    うまくいかない: 'うまくいきませんでした',
    AIが用意できない: 'AIの説明を用意できませんでした',
    // 「再試行してください」の言い換え。**できることを示す**形にする
    あとでためせる: '少し待ってから、もう一度ためせます',
    AIの調子: 'AIの調子がよくないようです',
    // 通信そのものが届かなかった時。番号は原因を伝える人のために残す
    通信できない: function (code) {
      return 'うまくいきませんでした' + (code ? '（' + code + '）' : '');
    }
  };

  /**
   * そのまま残す外来語（第40弾 1で確定）。
   * **和語に置き換えると、かえって分からなくなる語。**
   * 「プレイヤー」と同じ扱いで一貫させる。
   * 迷う語が増えたらここに足し、理由を書く。
   */
  var KEPT = [
    { 語: 'プレイヤー', 理由: 'すでに定着。遊ぶ人がこの語で認識している' },
    { 語: 'ログイン',   理由: '和語にすると操作が分からなくなる（「入る」は部屋に使っている）' },
    { 語: 'サーバー',   理由: '写真や記録の預け先を指す。置き換えると場所の話だと伝わらない' },
    { 語: 'データ',     理由: '記録・設定をまとめて指す語がほかにない' }
  ];

  /**
   * 遊び方の確認（第41弾 2-4）。
   *
   * カセットをえらんだ後に、1台でまわすか・みんなのスマホをつなぐかを決める。
   * **6通りのうち、聞くのは3通りだけ。**残りは素通りさせる。
   *
   * B（1台専用・部屋あり）の文面は、本人の裁定で決まった形。
   * 指示41 2-4 の当初案は「部屋はそのまま残ります」だったが、
   * それは**第33弾B-3で塞いだ穴を開け直す**ものだった——
   * 部屋に紐づいたまま手渡しへ進むと「もう一度」「ゲームを終了」が
   * 部屋側へ流れて状態が混ざる（実機で起きた）。
   * 安全策を外すには、その流れを作り直す独立した作業が要る。
   * いまは閉じてから進む。
   */
  var WAY = {
    // E：両方対応 × 部屋なし。どちらも肯定の選択肢（片方が逃げ道ではない）
    choose: {
      見出し: 'どうやって遊ぶ？',
      '1台': '1台のスマホで',
      '1台の説明': 'スマホをまわして遊びます',
      部屋: 'みんなのスマホで',
      部屋の説明: 'それぞれの端末で遊びます'
    },
    // C：部屋専用 × 部屋なし
    makeRoom: {
      見出し: 'みんなのスマホをつないで遊びます',
      本文: 'このカセットは、それぞれの端末で遊ぶ形です。部屋をつくります',
      進む: '部屋をつくる'
    },
    // B：1台専用 × 部屋あり（本人の裁定でこの形に確定）
    leaveRoom: {
      見出し: '1台のスマホをまわして遊びます',
      進行役の本文: 'このカセットは1台でまわす形です。いま開いている部屋を閉じます。部屋にいる全員が終わります',
      参加者の本文: 'このカセットは1台でまわす形です。いま入っている部屋からは抜けます',
      進行役の進む: '部屋を閉じて はじめる',
      参加者の進む: '部屋を抜けて はじめる'
    }
  };

  return { WORDS: WORDS, BANNED: BANNED, JARGON: JARGON, MSG: MSG, KEPT: KEPT, WAY: WAY };
}));
