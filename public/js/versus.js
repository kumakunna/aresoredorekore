// versus.js — **1v1の組をつくる**ことだけを担当する層（指示55-①・共通部品A）
//
// カセットをまたぐ共通部品なので、名前に接尾辞を付けない
// （fx.js / ui.js / titles.js / ui-text.js / emoji.js / qr.js と同じ列）。
//
// ---- なぜ新しく作ったか（判断の記録・指示55-① 判断①） ----
// 早押しトーナメントの勝ち抜き表（QuizLogic.newBracket）を土台にできないか、から始めた。
// 結論は「別部品」。ひとことで言うと：
//
//   **bracket は「勝った人だけが次へ上がる木を、1組ずつ順に消化する」。
//     この部品は「その回にいる全員を一斉に組にして、同時に回す」。**
//
// bracket の芯は matchIndex（いまのラウンドの何試合目か）というカーソル1本で、
// 同時回しではそれが常に 0 のまま使われない死に変数になる。拡張ではなく同居になる。
//
// **ただし「同時に複数組を回す」手本は、bracket ではなくすごろく「ふたりでひとつ」だった。**
// sugoroku-room.js:1427-1440 が部屋の deadline 1本で全組の段階を揃えている。
// 「同時回しだと部屋の時計1本では書けない」は誤りで、正しくは
// 「早押しは組ごとに締め切りがずれるから書けない。全組の段階を揃えるなら1本で足りる」。
//
// ---- 何を1つの正本にしたか（落とし穴1） ----
// 着手前に掃いたら、**同じことをする実装が既に3つ並走していた**：
//   ・QuizLogic.buildPairs / newBracket … 勝ち抜き・1組ずつ順に。奇数は不戦勝
//   ・SugorokuLogic.makePairs         … 全員を一斉に組へ・開始時1回だけ。奇数は3人組
//   ・FalseTrueLogic.opponentPool     … 未対面を優先・空なら全体へ戻す
// **奇数の扱いだけで3通り。**4つ目を作らないために：
//   ・buildPairs はここへ移し、quiz-logic.js が借りて再エクスポートする
//     （返り値の形 [[a,b],[c,null]] は1バイトも変えない。既存の検査がJSONで固定している）
//   ・余りの吸収は **'bye' か 'trio' を選べる**ようにしてある。
//     **sugopair はまだ乗せ替えていない**——乗せ替えたと誤読されないよう、ここに書いておく
//
// ---- なぜ②（進化じゃんけん）の要求まで見て形を決めたか ----
// 指示55-① の 2-4 は「絞り込みの条件を外から渡せる形」と書いていたが、
// それだけでは②のランク移動規則が**原理的に書けない**ことが着手前に分かった
// （本人の裁定 2026-09-19：②まで見て固める。①はその部分集合として使う）。
// 足りなかったのは4つで、どれもこのファイルの入口の形に入っている：
//   (1) 述語に名簿全体を渡す   … 「1人ランクかどうか」は2人を見ても判定できない
//   (2) 絞り込みではなく希望   … 絞り込みは候補を減らす道具で、**増やせない**。
//                                第1希望＝同ランク／第2希望＝1つ上、は段階でしか書けない
//   (3) 組に理由の印           … 「ランク違いの挑戦だ」と結果側が知らないと
//                                「勝てば2つ上・上の人は勝っても上がらない」が書けない
//   (4) 相手がいない理由を2種類 … 奇数の余り（→不戦勝）と、希望が全部空（→AI）は別物。
//                                [id,null] では区別できず、①の不戦勝と②のAIがぶつかる
//
// ブラウザからは window.Versus、Nodeからは require() で使える。

(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Versus = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /** 相手がいない理由。**この2つを取り違えると、不戦勝とAIがぶつかる** */
  var 理由なし = {
    余り: 'parity',        // 候補はいたが、この回は相手が余らなかった → 不戦勝
    候補ゼロ: 'no-candidate' // 希望を全部たどっても候補が1人もいない → ②はここでAIを出す
  };

  /** 組の既定の理由。呼ぶ側が希望に名前を付けなければこれになる */
  var 既定の理由 = '同格';

  /**
   * 混ぜる。**種つきの乱数を受け取れる**——秘匿の差分検査（同じ種で2局を回し、
   * 秘密だけを入れ替えて publicView を比べる）が書けなくなるので、
   * ここで Math.random を直に呼ばない。
   *
   * 現状 shuffled はリポジトリ全体に13か所ある。**ここで14個目を作らない**ために、
   * この部品を使う側はこれを借りる。
   */
  function shuffled(list, rnd) {
    var r = rnd || Math.random;
    var a = (list || []).slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(r() * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

  /**
   * 並んだ順に2人ずつ。奇数なら最後の1人は相方が null（＝不戦勝）。
   *
   * **quiz-logic.js から移してきた。**返り値の形は1バイトも変えていない——
   * tests/quiz-logic.js が JSON 文字列で固定していて、
   * 手渡し版の早押し（public/index.html の buildTourneyPairs）も同じ形を読む。
   * quiz-logic.js は `buildPairs: Versus.buildPairs` として借りて再エクスポートする。
   *
   * **ここは混ぜない。**混ぜるのは呼ぶ側（newBracket が shuffled してから渡す）。
   */
  function buildPairs(ids) {
    var pairs = [];
    for (var i = 0; i < ids.length; i += 2) {
      if (i + 1 < ids.length) pairs.push([ids[i], ids[i + 1]]);
      else pairs.push([ids[i], null]); // 奇数なら不戦勝
    }
    return pairs;
  }

  /** 名簿の1人分から id を取り出す。文字列そのものでも、{id} でも受ける */
  function idOf(x) { return (x && typeof x === 'object') ? x.id : x; }

  /**
   * **その回にいる全員を、一斉に1v1の組にする。**
   *
   * @param {Array} 名簿 `[{id, …}]`（id だけの文字列配列でもよい）。
   *   **希望・避ける には名簿の1人分がそのまま渡る**ので、ランクでも勝ち数でも好きに持たせてよい。
   * @param {object} opts
   *   - `希望` … `[{ 理由, 候補(名簿, 人) → 配列 }]` の**段階つきの希望**。
   *              第1希望で相手が見つからなければ第2希望へ落ちる。
   *              **渡さなければ「全体からランダム」**（①ロシアンカードはこれ）
   *   - `避ける(a, b)` … 真を返すと「できれば避ける」。**柔らかい条件**——
   *              避けない相手が1人もいなければ、避ける相手と組む
   *              （手本は FalseTrueLogic.opponentPool の「未対面が空なら全体へ戻す」）
   *   - `余りの吸収` … `'bye'`（既定・不戦勝を1人出す）か `'trio'`（3人組で吸収する）
   *   - `連続不戦勝を避ける` … 真なら、`直前の不戦勝` の人を**いちばん先に組ませる**
   *   - `直前の不戦勝` … 前の回に不戦勝だった人の id
   *   - `rnd` … 種つきの乱数
   * @returns {{組: Array, 相手なし: Array}}
   *   - `組` … `[{ a, b, c, 理由 }]`。`c` は 'trio' の時だけ id が入る（ふだんは null）
   *   - `相手なし` … `[{ id, なぜ }]`。`なぜ` は `'parity'`（不戦勝）か `'no-candidate'`（候補ゼロ）
   *
   * **硬い条件と柔らかい条件が、同ランクが2人しかいない部屋では必ずぶつかる。**
   * 折れる順番はこの部品が決めてある（ゲームごとに違う折れ方をさせない）：
   *   希望の段階（硬い） ＞ 連続不戦勝を避ける（硬い） ＞ 過去の相手を避ける（柔らかい）
   */
  function 組をつくる(名簿, opts) {
    var o = opts || {};
    var 全員 = (名簿 || []).slice();
    var 希望 = (o.希望 && o.希望.length) ? o.希望 : null;
    var 避ける = typeof o.避ける === 'function' ? o.避ける : null;
    var 吸収 = o.余りの吸収 === 'trio' ? 'trio' : 'bye';

    // ---- 段階つきの希望を1本の関数に畳む ----
    // 希望を渡さなければ「自分以外の全員が第1希望」。
    // **絞り込みではなく希望**なので、段階を下るほど候補は増えてよい（減らす道具ではない）
    var 段階 = 希望 || [{ 理由: 既定の理由, 候補: function (名簿, 人) {
      return 名簿.filter(function (x) { return idOf(x) !== idOf(人); });
    } }];

    /** その人の、段階ごとの候補id（自分は必ず外す） */
    function 候補たち(人, 段) {
      var 出 = 段.候補(全員, 人) || [];
      var 自分 = idOf(人);
      var 見た = {};
      return 出.map(idOf).filter(function (id) {
        if (!id || id === 自分 || 見た[id]) return false;
        見た[id] = true;
        return true;
      });
    }

    // ---- 型(b)の予防：**「候補が1人もいない人」を先に見分ける** ----
    // ここを greedy のあとで判定すると、「候補はいたが取られただけ」の人まで
    // 候補ゼロ扱いになり、②が出さなくてよいAIを出してしまう。
    // **候補ゼロ＝名簿全体に対して、どの段階でも候補が空**、と定義する。
    var 候補ゼロ = [];
    var 組める = [];
    全員.forEach(function (人) {
      var ある = 段階.some(function (段) { return 候補たち(人, 段).length > 0; });
      if (ある) 組める.push(人);
      else 候補ゼロ.push({ id: idOf(人), なぜ: 理由なし.候補ゼロ });
    });

    // ---- 並べる ----
    var 順 = shuffled(組める, o.rnd);
    // **連続不戦勝を避ける**：前回あぶれた人をいちばん先に組ませる。
    // 「あとで余った人を選び直す」形にしないのは、希望の段階があると
    // 「選び直せる相手がもういない」場面が作れてしまうから（落とし穴8：片方向にしか効かない）
    if (o.連続不戦勝を避ける && o.直前の不戦勝) {
      var 先 = 順.filter(function (x) { return idOf(x) === o.直前の不戦勝; });
      if (先.length) {
        順 = 先.concat(順.filter(function (x) { return idOf(x) !== o.直前の不戦勝; }));
      }
    }

    // ---- 貪欲に組む ----
    var 空き = {};
    順.forEach(function (x) { 空き[idOf(x)] = x; });
    var 組 = [];
    順.forEach(function (人) {
      var 自分 = idOf(人);
      if (!空き[自分]) return;            // もう組んだ
      for (var i = 0; i < 段階.length; i++) {
        var 段 = 段階[i];
        var 空いている = 候補たち(人, 段).filter(function (id) {
          return id !== 自分 && !!空き[id];
        });
        if (!空いている.length) continue;  // この段階では見つからない → 次の希望へ
        // **柔らかい条件はここで折る**：避けない相手がいればそちらを、いなければ全部から
        var 好み = 避ける
          ? 空いている.filter(function (id) { return !避ける(人, 空き[id]); })
          : 空いている;
        var 相手 = (好み.length ? 好み : 空いている)[0];
        delete 空き[自分]; delete 空き[相手];
        組.push({ a: 自分, b: 相手, c: null, 理由: 段.理由 || 既定の理由 });
        return;
      }
      // どの段階でも空いている相手が見つからなかった。**ここでは何もしない**——
      // 余りの扱いは下でまとめて決める（候補ゼロと取り違えないため）
    });
    // ---- 余りを吸収する ----
    var 余り = Object.keys(空き);
    var 相手なし = 候補ゼロ.slice();
    if (余り.length) {
      if (吸収 === 'trio' && 組.length) {
        // **3人組で吸収する**（すごろく「ふたりでひとつ」の型）。
        // 余りを既存の組へ1人ずつ足す。組より余りが多ければ、残りは不戦勝に落とす
        余り.forEach(function (id, i) {
          var 先 = 組[i % 組.length];
          if (先 && !先.c) 先.c = id;
          else 相手なし.push({ id: id, なぜ: 理由なし.余り });
        });
      } else {
        余り.forEach(function (id) { 相手なし.push({ id: id, なぜ: 理由なし.余り }); });
      }
    }
    return { 組: 組, 相手なし: 相手なし };
  }

  return {
    理由なし: 理由なし,
    既定の理由: 既定の理由,
    shuffled: shuffled,
    buildPairs: buildPairs,
    組をつくる: 組をつくる
  };
});
