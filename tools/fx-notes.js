function 注釈(r) {
  let n = null;
  if (r.種 === 'fx') n = 行[r.鍵.replace(/^(\w+)@/, '$1@')] || (既定[r.部品] && 既定[r.部品](r));
  else if (r.種 === 'snd') n = 行[r.鍵];
  else if (r.種 === 'vib') n = 行[r.鍵];
  else if (r.種 === 'css') n = 動き[r.部品];
  else if (r.種 === 'tr') n = 遷移(r.選択子, r.宣言);
  else if (r.種 === 'act') n = 情('押した手ごたえ（' + r.選択子.slice(0, 40) + '）', '押せたこと（指の下で反応した）');
  return n || 迷('（未分類）' + (r.部品 || r.選択子), '—', 'まだ読んでいない');
}

