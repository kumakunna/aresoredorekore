function 遷移(sel, decl) {
  if (/\.app\.theme-/.test(sel)) return 賑('世界（カセット）が変わる時の色の移り');
  if (/^\.app\.theme-wolf$/.test(sel)) return 賑('人狼の地の色の移り');
  if (/:active|^button$|^\.btn$|\.ui-btn|\.ui-chip|\.set-row|\.next-card|\.tier-card|slider-thumb|range-thumb|\.wheel-item|\.mode-card$/.test(sel)) return 情('押した手ごたえ（沈む・明るくなる）の動き', '押せたこと');
  if (/\.switch/.test(sel)) return 情('切り替えスイッチが動く', 'ON／OFF が変わったこと');
  if (/hold-ring/.test(sel)) return 情('長押しの輪が溜まる', 'あとどれだけ押せばいいか');
  if (/fill/.test(sel)) return 情('進み具合のバーが伸びる', 'どこまで進んだか');
  if (/\.rk-row/.test(sel)) return 情('順位表の行が入れ替わる', '順位の上下');
  if (/fx-fly-go/.test(sel)) return 迷('飛ぶ印の動き（FxKit.fly）', '何がどこへ行ったか', 'fly の行と同じ');
  if (/fx-notice|ui-toast|title-toast|foul-toast/.test(sel)) return 賑('知らせが出入りする動き', '（知らせの文字そのものは出る）');
  if (/ui-layer|ui-dim|ui-dialog|ui-popup|ui-sheet|tut-root/.test(sel)) return 賑('重なり（ダイアログ・シート）の出入り', '（出ること自体は分かる）');
  if (/door/.test(sel)) return 賑('起動の扉');
  if (/cart|rail|shelf-stage|cassette-warp|cart-meta/.test(sel)) return 迷('棚：カセットが動く・色が移る', 'どのカセットが真ん中か', '情報：送った先が分かる。賑やかし：位置は止まった後も分かる');
  if (/\.mode-card$/.test(sel)) return 情('選んだ札の枠の色', 'どれを選んだか');
  return 迷('動き（' + sel + '）', '—', '見立てが付かなかった');
}

