線('[1] 組の a は必ず「下の段（挑戦者）」か');
{
  let 総組 = 0, 上組 = 0, 逆 = 0, 同ランクなのに段違い = 0;
  const 例 = [];
  for (let seed = 1; seed <= 4000; seed++) {
    const rnd = mulberry32(seed);
    // 段をばらばらに配る（1〜5段、3〜9人）
    const 人数 = 3 + Math.floor(rnd() * 7);
    const 名簿 = [];
    for (let i = 0; i < 人数; i++) 名簿.push({ id: 'P' + (i + 1), 段: 1 + Math.floor(rnd() * 5) });
    const 段 = 段表(名簿);
    const res = 回す(名簿, { rnd: mulberry32(seed * 7 + 1) });
    res.組.forEach((g) => {
      総組++;
      if (g.理由 === '1つ上') {
        上組++;
        if (段[g.a] + 1 !== 段[g.b]) {
          逆++;
          if (例.length < 3) 例.push(JSON.stringify(g) + ' 段:' + 段[g.a] + '→' + 段[g.b]);
        }
      } else if (g.理由 === '同ランク' && 段[g.a] !== 段[g.b]) {
        同ランクなのに段違い++;
      }
    });
  }
  console.log('組の総数 ' + 総組 + ' / うち 理由:1つ上 が ' + 上組);
  console.log('「a が下の段」に反した組： ' + 逆 + ' 件');
  console.log('「同ランク」なのに段が違った組： ' + 同ランクなのに段違い + ' 件');
  if (例.length) console.log('例: ' + 例.join(' | '));
}

