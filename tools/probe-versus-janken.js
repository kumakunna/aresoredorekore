const 希望 = [
  { 理由: '同ランク', 候補: (名簿, 人) => 名簿.filter((x) => x.段 === 人.段) },
  { 理由: '1つ上',   候補: (名簿, 人) => 名簿.filter((x) => x.段 === 人.段 + 1) }
];

function 名簿を作る(分布) {
  // 分布 = { 段: 人数 } → [{id, 段}]
  const out = [];
  let n = 0;
  Object.keys(分布).forEach((段) => {
    for (let i = 0; i < 分布[段]; i++) out.push({ id: 'P' + (++n), 段: Number(段) });
  });
  return out;
}
const 段表 = (名簿) => {
  const m = {};
  名簿.forEach((x) => { m[x.id] = x.段; });
  return m;
};

function 回す(名簿, opts) {
  return Versus.組をつくる(名簿, Object.assign({ 希望: 希望, 余りの吸収: 'bye' }, opts || {}));
}

