// [4] 避ける：'直前だけ' と '過去ぜんぶ' の差
// ================================================================
線("[4] 避ける＝'直前だけ' vs '過去ぜんぶ'（候補は枯れるか・同じ組の再現率）");
{
  function 走る(モード, 人数, 回数, seed) {
    const 名簿 = 名簿を作る({ 1: 人数 });   // 全員が同じ段＝②でいちばん起きる形
    const faced = {};
    名簿.forEach((x) => { faced[x.id] = []; });
    let 直前 = {};
    let 連続再戦 = 0, 総組 = 0, 相手なし = 0;
    const 組数え = {};
    const rnd = mulberry32(seed);
    for (let r = 0; r < 回数; r++) {
      const 避ける = モード === '直前だけ'
        ? (a, b) => 直前[a.id] === b.id
        : (a, b) => (faced[a.id] || []).indexOf(b.id) !== -1;
      const res = Versus.組をつくる(名簿, { 希望: 希望, 避ける: 避ける, 余りの吸収: 'bye', rnd: rnd });
      const 次直前 = {};
      res.組.forEach((g) => {
        総組++;
        if (直前[g.a] === g.b) 連続再戦++;
        次直前[g.a] = g.b; 次直前[g.b] = g.a;
        faced[g.a].push(g.b); faced[g.b].push(g.a);
        const k = [g.a, g.b].sort().join('-');
        組数え[k] = (組数え[k] || 0) + 1;
      });
      相手なし += res.相手なし.length;
      直前 = 次直前;
    }
    const 全組 = Object.keys(組数え).length;
    const 可能 = (人数 * (人数 - 1)) / 2;
    const 偏り = Object.keys(組数え).map((k) => 組数え[k]);
    return {
      総組: 総組, 連続再戦: 連続再戦, 相手なし: 相手なし,
      出た組: 全組 + '/' + 可能,
      最多: Math.max.apply(null, 偏り), 最少: Math.min.apply(null, 偏り)
    };
  }
  [4, 5, 6, 8].forEach((n) => {
    ['直前だけ', '過去ぜんぶ'].forEach((m) => {
      const o = 走る(m, n, 40, 12345);
      console.log(
        (n + '人 ' + m).padEnd(16)
        + ' 組' + String(o.総組).padStart(3)
        + ' 連続再戦 ' + String(o.連続再戦).padStart(3)
        + ' 相手なし ' + String(o.相手なし).padStart(3)
        + ' 出た組の種類 ' + o.出た組
        + ' （同じ組が最多 ' + o.最多 + '回 / 最少 ' + o.最少 + '回）'
      );
    });
  });
}

